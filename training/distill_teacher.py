"""Generate verified teacher solutions with Qwen3.5 9B (Apache-2.0) for adapter 0.2.

For each *train-split* problem the 9B solves it exactly as Thrones runs it (system prompt + real
calculator tool, thinking off). A solution is kept only if it is verified: maths answers must equal
the dataset's gold answer, code must pass the problem's own unit tests. Failed problems get one
sampled retry (temperature 0.7). Output is appended as it goes so the run can resume.

    .venv-train\\Scripts\\python training\\distill_teacher.py
"""
from __future__ import annotations

import argparse
import json
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "evals"))
sys.path.insert(0, str(ROOT / "backend"))
sys.path.insert(0, str(ROOT / "training"))

import reasoning_sets as rs  # noqa: E402
from run_bench import BASE, Server, free_app_engine  # noqa: E402
from thrones import config  # noqa: E402

OUT = ROOT / "training" / "datasets" / "distill_v0.2.jsonl"
SLOTS = 6


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gsm8k", type=int, default=300)
    ap.add_argument("--math", type=int, default=500)
    ap.add_argument("--seed", type=int, default=20261113)
    args = ap.parse_args()

    import build_dataset_v02 as b  # system prompt identical to the training rows
    system = b.system()

    items = (rs.sample(rs.gsm8k("train"), args.gsm8k, args.seed)
             + rs.sample([m for m in rs.math_int("train") if m["level"] in ("Level 4", "Level 5")], args.math, args.seed)
             + rs.mbpp(("train", "validation", "prompt")))
    done = set()
    if OUT.exists():
        for line in OUT.open(encoding="utf-8"):
            done.add(json.loads(line)["meta"]["item_id"])
    todo = [it for it in items if it["id"] not in done and f"skip:{it['id']}" not in done]
    print(f"{len(items)} problems, {len(done)} already processed, {len(todo)} to go", flush=True)

    entry = next(e for e in config.load_catalog() if e["id"] == "qwen3.5-9b-q4km")
    client = httpx.Client(timeout=900)
    lock = threading.Lock()
    stats = {"kept": 0, "failed": 0, "retry_saved": 0}

    def post(body: dict) -> dict:
        r = client.post(BASE + "/v1/chat/completions", json=body)
        r.raise_for_status()
        return r.json()["choices"][0]

    def one(item: dict) -> None:
        msgs = [{"role": "system", "content": system}, {"role": "user", "content": item["prompt"]}]
        kept = None
        for attempt, temp in enumerate((0.0, 0.7)):
            produced, final = rs.solve(post, msgs, rs.TOOLS, max_tokens=1500, temperature=temp)
            tool_errors = any(m["role"] == "tool" and m["content"].startswith("Error") for m in produced)
            if final and len(final) < 5000 and not tool_errors and rs.grade(item, final):
                kept = (produced, attempt)
                break
        with lock:
            with OUT.open("a", encoding="utf-8") as f:
                if kept:
                    produced, attempt = kept
                    stats["kept"] += 1
                    stats["retry_saved"] += attempt == 1
                    f.write(json.dumps({
                        "messages": msgs + produced, "tools": rs.TOOLS,
                        "meta": {"kind": f"distill_{item['kind']}", "item_id": item["id"],
                                 "source": item["source"], "license": item["license"],
                                 "origin": "problem from the dataset; solution generated by Qwen3.5 9B "
                                           "(Apache-2.0) with the Thrones calculator and verified "
                                           + ("by the problem's unit tests" if item["kind"] == "mbpp"
                                              else "against the dataset's gold answer"),
                                 "transform": f"attempt {attempt + 1}"}}, ensure_ascii=False) + "\n")
                else:
                    stats["failed"] += 1
                    f.write(json.dumps({"meta": {"item_id": f"skip:{item['id']}"}}) + "\n")
                n = stats["kept"] + stats["failed"]
                if n % 100 == 0:
                    print(f"  {n}/{len(todo)} processed, kept {stats['kept']} (retry saved {stats['retry_saved']}), "
                          f"failed {stats['failed']}", flush=True)

    free_app_engine()
    t0 = time.time()
    with Server(entry, 8192 * SLOTS, 99, ["-np", str(SLOTS)]):
        with ThreadPoolExecutor(SLOTS) as pool:
            list(pool.map(one, todo))
    print(f"done in {time.time() - t0:.0f}s: {stats}", flush=True)


if __name__ == "__main__":
    main()
